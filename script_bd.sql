COMMENT ON COLUMN T_CLYVO_VACINA_ANIMAL.dt_receita IS 'Data em que a vacina foi aplicada';
COMMENT ON COLUMN T_CLYVO_VACINA_ANIMAL.fk_id_vacina IS 'Chave estrangeira para a vacina aplicada';
COMMENT ON COLUMN T_CLYVO_VACINA_ANIMAL.fk_id_animal IS 'Chave estrangeira para o animal vacinado';

CREATE TABLE T_CLYVO_CONSULTA (
    id_consulta NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dt_agendamento DATE,
    dt_consulta DATE NOT NULL,
    fk_id_animal NUMBER(19,0),
    fk_id_veterinario NUMBER(19,0),
    CONSTRAINT fk_consulta_animal FOREIGN KEY (fk_id_animal) REFERENCES T_CLYVO_ANIMAL(id_animal),
    CONSTRAINT fk_consulta_veterinario FOREIGN KEY (fk_id_veterinario) REFERENCES T_CLYVO_VETERINARIO(id_veterinario)
);

COMMENT ON TABLE T_CLYVO_CONSULTA IS 'Consulta veterinaria agendada para um animal com um veterinario';
COMMENT ON COLUMN T_CLYVO_CONSULTA.id_consulta IS 'Identificador unico da consulta';
COMMENT ON COLUMN T_CLYVO_CONSULTA.dt_agendamento IS 'Data em que a consulta foi agendada';
COMMENT ON COLUMN T_CLYVO_CONSULTA.dt_consulta IS 'Data em que a consulta sera realizada';
COMMENT ON COLUMN T_CLYVO_CONSULTA.fk_id_animal IS 'Chave estrangeira para o animal da consulta';
COMMENT ON COLUMN T_CLYVO_CONSULTA.fk_id_veterinario IS 'Chave estrangeira para o veterinario responsavel';

CREATE TABLE T_CLYVO_HISTORICO (
    id_historico NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_historico CLOB,
    dt_criacao_historico DATE,
    num_consultas_clyvo NUMBER,
    fk_id_consulta NUMBER(19,0),
    fk_id_animal NUMBER(19,0),
    CONSTRAINT fk_historico_consulta FOREIGN KEY (fk_id_consulta) REFERENCES T_CLYVO_CONSULTA(id_consulta),
    CONSTRAINT fk_historico_animal FOREIGN KEY (fk_id_animal) REFERENCES T_CLYVO_ANIMAL(id_animal)
