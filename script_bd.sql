CREATE TABLE T_CLYVO_RESPONSAVEL (
    id_responsavel NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nm_responsavel VARCHAR2(50) NOT NULL,
    cpf VARCHAR2(14),
    dt_nascimento DATE,
    email VARCHAR2(50) NOT NULL,
    num_celular VARCHAR2(20) NOT NULL
);

COMMENT ON TABLE T_CLYVO_RESPONSAVEL IS 'Pessoa responsavel legal por um ou mais animais cadastrados no sistema';
COMMENT ON COLUMN T_CLYVO_RESPONSAVEL.id_responsavel IS 'Identificador unico do responsavel';
COMMENT ON COLUMN T_CLYVO_RESPONSAVEL.nm_responsavel IS 'Nome completo do responsavel';
COMMENT ON COLUMN T_CLYVO_RESPONSAVEL.cpf IS 'CPF do responsavel';
COMMENT ON COLUMN T_CLYVO_RESPONSAVEL.dt_nascimento IS 'Data de nascimento do responsavel';
COMMENT ON COLUMN T_CLYVO_RESPONSAVEL.email IS 'E-mail de contato do responsavel';
COMMENT ON COLUMN T_CLYVO_RESPONSAVEL.num_celular IS 'Telefone de contato do responsavel';

CREATE TABLE T_CLYVO_VETERINARIO (
    id_veterinario NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nm_veterinario VARCHAR2(50) NOT NULL,
    cpf VARCHAR2(14),
