COMMENT ON COLUMN T_CLYVO_HISTORICO.num_consultas_clyvo IS 'Numero de consultas registradas no sistema para o animal';
COMMENT ON COLUMN T_CLYVO_HISTORICO.fk_id_consulta IS 'Chave estrangeira para a consulta de origem';
COMMENT ON COLUMN T_CLYVO_HISTORICO.fk_id_animal IS 'Chave estrangeira para o animal do historico';

