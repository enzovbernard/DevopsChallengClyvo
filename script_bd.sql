COMMENT ON COLUMN T_CLYVO_VETERINARIO.nm_veterinario IS 'Nome completo do veterinario';
COMMENT ON COLUMN T_CLYVO_VETERINARIO.cpf IS 'CPF do veterinario';
COMMENT ON COLUMN T_CLYVO_VETERINARIO.dt_nascimento IS 'Data de nascimento do veterinario';
COMMENT ON COLUMN T_CLYVO_VETERINARIO.email IS 'E-mail de contato do veterinario';
COMMENT ON COLUMN T_CLYVO_VETERINARIO.num_celular IS 'Telefone de contato do veterinario';
COMMENT ON COLUMN T_CLYVO_VETERINARIO.especialidade IS 'Area de especializacao do veterinario';

CREATE TABLE T_CLYVO_ANIMAL (
    id_animal NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nm_animal VARCHAR2(50),
    idade NUMBER(10,0),
    especie VARCHAR2(50),
    raca VARCHAR2(50),
    sexo VARCHAR2(1),
    dt_nascimento DATE,
    peso NUMBER,
    fk_id_responsavel NUMBER(19,0),
    CONSTRAINT fk_animal_responsavel FOREIGN KEY (fk_id_responsavel) REFERENCES T_CLYVO_RESPONSAVEL(id_responsavel)
);

COMMENT ON TABLE T_CLYVO_ANIMAL IS 'Animal domestico cadastrado no sistema, vinculado a um responsavel';
COMMENT ON COLUMN T_CLYVO_ANIMAL.id_animal IS 'Identificador unico do animal';
COMMENT ON COLUMN T_CLYVO_ANIMAL.nm_animal IS 'Nome do animal';
COMMENT ON COLUMN T_CLYVO_ANIMAL.idade IS 'Idade do animal em anos';
COMMENT ON COLUMN T_CLYVO_ANIMAL.especie IS 'Especie do animal';
COMMENT ON COLUMN T_CLYVO_ANIMAL.raca IS 'Raca do animal';
COMMENT ON COLUMN T_CLYVO_ANIMAL.sexo IS 'Sexo do animal: M para macho, F para femea';
COMMENT ON COLUMN T_CLYVO_ANIMAL.dt_nascimento IS 'Data de nascimento do animal';
COMMENT ON COLUMN T_CLYVO_ANIMAL.peso IS 'Peso atual do animal em quilogramas';
COMMENT ON COLUMN T_CLYVO_ANIMAL.fk_id_responsavel IS 'Chave estrangeira para o responsavel legal do animal';

