CREATE TABLE T_CLYVO_DOENCA_ANIMAL (
    id_doenca_animal NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dt_diagnostico DATE,
    gravidade VARCHAR2(50),
    status VARCHAR2(50),
    observacoes CLOB,
    fk_id_animal NUMBER(19,0),
    fk_id_doenca NUMBER(19,0),
    CONSTRAINT fk_doencaanimal_animal FOREIGN KEY (fk_id_animal) REFERENCES T_CLYVO_ANIMAL(id_animal),
    CONSTRAINT fk_doencaanimal_doenca FOREIGN KEY (fk_id_doenca) REFERENCES T_CLYVO_DOENCA(id_doenca)
);

COMMENT ON TABLE T_CLYVO_DOENCA_ANIMAL IS 'Registro de diagnostico de uma doenca em um animal especifico';
COMMENT ON COLUMN T_CLYVO_DOENCA_ANIMAL.id_doenca_animal IS 'Identificador unico do diagnostico';
COMMENT ON COLUMN T_CLYVO_DOENCA_ANIMAL.dt_diagnostico IS 'Data em que o diagnostico foi realizado';
COMMENT ON COLUMN T_CLYVO_DOENCA_ANIMAL.gravidade IS 'Gravidade do quadro diagnosticado';
COMMENT ON COLUMN T_CLYVO_DOENCA_ANIMAL.status IS 'Status do tratamento da doenca';
COMMENT ON COLUMN T_CLYVO_DOENCA_ANIMAL.observacoes IS 'Observacoes clinicas sobre o diagnostico';
COMMENT ON COLUMN T_CLYVO_DOENCA_ANIMAL.fk_id_animal IS 'Chave estrangeira para o animal diagnosticado';
COMMENT ON COLUMN T_CLYVO_DOENCA_ANIMAL.fk_id_doenca IS 'Chave estrangeira para a doenca diagnosticada';

CREATE TABLE T_CLYVO_VACINA_ANIMAL (
    id_vacina_animal NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    num_doses NUMBER(10,0),
    frequencia_aplicacao NUMBER(10,0),
    dt_receita DATE,
